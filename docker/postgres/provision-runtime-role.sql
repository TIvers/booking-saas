SELECT format(
    'CREATE ROLE booking_app WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS',
    :'runtime_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'booking_app')
\gexec

ALTER ROLE booking_app WITH
    LOGIN PASSWORD :'runtime_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

GRANT USAGE ON SCHEMA public TO booking_app;
REVOKE CREATE ON SCHEMA public FROM booking_app;

ALTER DEFAULT PRIVILEGES FOR ROLE booking IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO booking_app;

ALTER DEFAULT PRIVILEGES FOR ROLE booking IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO booking_app;
